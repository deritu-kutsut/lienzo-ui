// Windows resources of the executable: icon, version strings and the application manifest.
// The manifest asks for per-monitor-v2 DPI awareness, long paths and Windows 10/11, and never asks for elevation.
// It also links with /CETCOMPAT on MSVC (hardware shadow stack compatibility); control-flow guard is a rustc flag,
// see .cargo/config.toml and publicar.sh.

#[cfg(windows)]
const MANIFEST: &str = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity type="win32" name="Lienzo.UI" version="1.0.0.0"/>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security>
      <requestedPrivileges>
        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>
      </requestedPrivileges>
    </security>
  </trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <!-- Windows 10 and Windows 11 -->
      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>
    </application>
  </compatibility>
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>
      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
      <longPathAware xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">true</longPathAware>
    </windowsSettings>
  </application>
</assembly>
"#;

/// Writes `$OUT_DIR/pack_table.rs`: one `include_bytes!` per file listed in `assets/pack/manifest.json`
/// (the built-in asset pack, see docs/CONTENT.md). std only: the manifest is scanned for its `"file"` values.
fn generate_pack_table() {
    println!("cargo:rerun-if-changed=assets/pack");
    let root = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let manifest = std::fs::read_to_string(root.join("assets/pack/manifest.json")).unwrap_or_else(|e| panic!("assets/pack/manifest.json: {e}"));
    let mut files: Vec<String> = Vec::new();
    let mut rest = manifest.as_str();
    while let Some(i) = rest.find("\"file\"") {
        rest = &rest[i + 6..];
        let Some(colon) = rest.find(':') else { break };
        let after = rest[colon + 1..].trim_start();
        let Some(body) = after.strip_prefix('"') else { continue };
        let Some(end) = body.find('"') else { break };
        let f = &body[..end];
        if !files.iter().any(|x| x == f) {
            files.push(f.to_string());
        }
        rest = &body[end..];
    }
    let mut out = String::from("// generated by build.rs from assets/pack/manifest.json\npub static PACK_FILES: &[(&str, &[u8])] = &[\n");
    for f in &files {
        let abs = root.join("assets/pack").join(f);
        assert!(abs.is_file(), "assets/pack/manifest.json lists {f}, which does not exist");
        let abs = abs.to_string_lossy().replace("\\", "/");
        out.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", f, abs));
    }
    out.push_str("];\n");
    let dest = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("pack_table.rs");
    std::fs::write(dest, out).expect("write pack_table.rs");
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    generate_pack_table();
    println!("cargo:rerun-if-changed=assets/brand/icon.ico");
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg-bins=/CETCOMPAT");
    }
    #[cfg(windows)]
    {
        let mut res = winresource::WindowsResource::new();
        res.set_icon("assets/brand/icon.ico");
        res.set("ProductName", "Lienzo UI");
        res.set("FileDescription", "Lienzo UI · design interfaces for Unity");
        res.set_manifest(MANIFEST);
        if let Err(e) = res.compile() {
            println!("cargo:warning=could not embed the icon and manifest: {e}");
        }
    }
}
